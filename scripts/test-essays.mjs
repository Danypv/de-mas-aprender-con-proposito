import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import matter from 'gray-matter';
import {essayCategories,renderEssayBody,readEssays} from './essays.mjs';

const source=process.cwd(),root=fs.mkdtempSync(path.join(os.tmpdir(),'demas-essays-'));
const text=Array.from({length:12},(_,i)=>`Párrafo ${i+1}. Esta reflexión desarrolla una idea sobre el deseo y la responsabilidad de juzgar con razones propias.`).join('\n\n');
const base={title:'Platón y el eros',slug:'platon-y-el-eros',author:'Autora invitada',date:'2026-11-04',summary:'Una reflexión filosófica.',status:'published',categories:['filosofia'],author_url:'https://orcid.org/0000-0000-0000-0000'};
const write=(file,data)=>{const target=path.join(root,file);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,data)};
const save=(name,data,body=text)=>write(`content/essays/${name}.md`,matter.stringify(body,data));
const run=name=>execFileSync(process.execPath,[`scripts/${name}.mjs`],{cwd:root,stdio:'pipe'});
const html=file=>fs.readFileSync(path.join(root,file),'utf8');
const home=()=>html('index.html').match(/<!-- ESSAYS_START -->([\s\S]*?)<!-- ESSAYS_END -->/)[1];
const build=()=>{for(const name of ['build-content','build-essays','build-readings','build-videos','build-podcasts','build-latest','build-sitemap','build-search','check-search'])run(name)};
try{
  for(const dir of ['scripts','templates'])fs.cpSync(path.join(source,dir),path.join(root,dir),{recursive:true});
  fs.symlinkSync(path.join(source,'node_modules'),path.join(root,'node_modules'),'dir');
  fs.copyFileSync(path.join(source,'package.json'),path.join(root,'package.json'));
  fs.copyFileSync(path.join(source,'index.html'),path.join(root,'index.html'));
  fs.mkdirSync(path.join(root,'blog'));fs.copyFileSync(path.join(source,'blog/index.html'),path.join(root,'blog/index.html'));
  for(const dir of ['essays','posts'])fs.mkdirSync(path.join(root,'content',dir),{recursive:true});
  const labels=essayCategories.map(c=>c.title);
  assert.deepEqual(labels,[...labels].sort((a,b)=>a.localeCompare(b,'es',{sensitivity:'base'})));
  assert.equal(labels.length,13);assert(labels.includes('Empresa')&&labels.includes('Cultura'));
  const rendered=renderEssayBody(text,base.slug);
  assert.equal((rendered.match(/class="destacado-editorial"/g)||[]).length,2);
  assert.equal(renderEssayBody(text,base.slug),rendered);
  assert(!/<p class="destacado-editorial">Párrafo (1|12)\./.test(rendered));
  assert(!renderEssayBody('Un texto breve.',base.slug).includes('destacado-editorial'));
  build();assert(home().includes('Próximamente'));assert(!home().includes('<img'));assert(home().includes('Pensar a fondo</h2>'));
  const fullHome=html('index.html');assert(fullHome.indexOf('id="lecturas"')<fullHome.indexOf('id="ensayos"'));assert(fullHome.indexOf('id="ensayos"')<fullHome.indexOf('id="formatos"'));
  save('invitada',base);
  save('privado',{...base,slug:'privado',date:'2027-01-01',status:'draft'},'secretoprivadoensayo');
  write('content/posts/relacionado.md',matter.stringify('Un artículo afín.',{...base,slug:'articulo-afin',categories:['Filosofía']}));
  build();
  const article=html('ensayos/platon-y-el-eros/index.html');
  assert(article.includes('href="https://orcid.org/0000-0000-0000-0000"'));
  assert(article.includes('<strong>Autora invitada</strong><a class="perfil-autor"'));
  assert.equal((article.match(/class="destacado-editorial"/g)||[]).length,2);
  assert(article.includes('https://somosdemas.com/ensayos/platon-y-el-eros/'));
  assert(article.includes('class="compartir"')&&article.includes('class="relacionados"'));
  assert(html('blog/articulo-afin/index.html').includes('class="relacionado" href="/ensayos/platon-y-el-eros/"'));
  assert(home().includes(base.title)&&!home().includes('Último ensayo'));
  assert(!fs.existsSync(path.join(root,'ensayos/privado/index.html')));
  let manifest=JSON.parse(html('assets/busqueda/manifest.json'));
  assert(manifest.entries.some(item=>item.url==='/ensayos/platon-y-el-eros/'&&item.section==='Ensayos'));
  assert(!manifest.entries.some(item=>item.url.includes('/privado/')));
  // A later publication takes the whole home feature, even if the earlier
  // record happens to carry a legacy featured flag.
  write('assets/imagenes/blog/portada.webp',fs.readFileSync(path.join(source,'assets/imagenes/ficha-partenon.webp')));
  save('invitada',{...base,featured:true});
  save('nueva',{...base,slug:'nuevo-ensayo',title:'Otra mirada',date:'2026-11-05',categories:['arte','cultura'],author_url:'https://www.linkedin.com/in/autora/',cover:'/assets/imagenes/blog/portada.webp',cover_alt:'Imagen horizontal de portada'});
  build();assert(home().includes('Otra mirada'));assert(home().includes('src="/assets/imagenes/blog/portada.webp"'));assert(!home().includes(base.title));
  const newest=html('ensayos/nuevo-ensayo/index.html');assert(newest.includes('property="og:image" content="https://somosdemas.com/assets/imagenes/blog/portada.webp"'));assert(newest.includes('>LinkedIn '));
  save('nueva',{...base,slug:'nuevo-ensayo',title:'Título editado',date:'2026-11-05',categories:['empresa'],author_url:''});
  build();assert(home().includes('Título editado'));assert(!html('ensayos/nuevo-ensayo/index.html').includes('class="perfil-autor"'));
  fs.unlinkSync(path.join(root,'content/essays/nueva.md'));build();
  assert(!fs.existsSync(path.join(root,'ensayos/nuevo-ensayo/index.html')));assert(home().includes(base.title));
  fs.unlinkSync(path.join(root,'content/essays/invitada.md'));build();
  assert(home().includes('Próximamente'));assert(!fs.existsSync(path.join(root,'ensayos/platon-y-el-eros/index.html')));
  assert(!html('sitemap.xml').includes('/ensayos/platon-y-el-eros/'));
  assert(!html('blog/articulo-afin/index.html').includes('class="relacionado" href="/ensayos/platon-y-el-eros/"'));
  manifest=JSON.parse(html('assets/busqueda/manifest.json'));assert(!manifest.entries.some(item=>item.url==='/ensayos/platon-y-el-eros/'));
  save('invalid',{...base,categories:['inexistente']});assert.throws(()=>readEssays(root),/tema válido/);
  console.log('Ensayos: vacío inicial, categorías, autor opcional, destacados estables, novedades, edición, privacidad, búsqueda, recomendaciones, retirada y regreso al estado vacío verificados.');
}finally{fs.rmSync(root,{recursive:true,force:true})}
