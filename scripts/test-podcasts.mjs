import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import matter from 'gray-matter';
import {readPodcasts} from './podcasts.mjs';
const root=process.cwd();const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'demas-podcast-'));
try{
 for(const dir of ['scripts','templates'])fs.cpSync(path.join(root,dir),path.join(fixture,dir),{recursive:true});
 fs.symlinkSync(path.join(root,'node_modules'),path.join(fixture,'node_modules'),'dir');
 for(const dir of ['podcast-series','podcast-episodes'])fs.mkdirSync(path.join(fixture,'content',dir),{recursive:true});
 const save=(dir,name,data,body='Notas del episodio.')=>fs.writeFileSync(path.join(fixture,'content',dir,name),matter.stringify(body,Object.fromEntries(Object.entries(data).filter(([,v])=>v!==undefined))));
 const series={title:'Serie de prueba',slug:'serie-prueba',presenter:'Voz de prueba',summary:'Descripción de la serie',status:'published'};
 const episode={title:'Episodio <especial> $&',slug:'episodio-prueba',series:'serie-prueba',summary:'Descripción del episodio',status:'published',date:'2026-10-16',audio_url:'https://example.org/audio.mp3',transcript:'Una transcripción de prueba.'};
 save('podcast-series','serie.md',series);
 save('podcast-episodes','audio.md',episode);
 save('podcast-episodes','spotify.md',{...episode,slug:'spotify-prueba',audio_url:undefined,spotify_url:'https://open.spotify.com/episode/123abc?si=prueba'});
 save('podcast-episodes','draft.md',{...episode,slug:'borrador-privado',status:'draft'});
 const build=()=>execFileSync(process.execPath,['scripts/build-podcasts.mjs'],{cwd:fixture,stdio:'pipe'});
 build();
 const page=p=>fs.readFileSync(path.join(fixture,p),'utf8');
 assert(page('podcast/index.html').includes('Nuestras series.'));
 const audio=page('podcast/episodios/episodio-prueba/index.html');
 assert(audio.includes('<audio controls preload="none"'));
 assert(!audio.includes('autoplay'));
 assert(audio.includes('Leer la transcripción'));
 assert(audio.includes('Episodio &lt;especial&gt; $&'));
 assert(!/\{\{[A-Z_]+\}\}/.test(audio));
 assert(page('podcast/episodios/spotify-prueba/index.html').includes('https://open.spotify.com/embed/episode/123abc'));
 assert(!fs.existsSync(path.join(fixture,'podcast/episodios/borrador-privado')));
 const before=page('podcast/index.html');build();assert.equal(page('podcast/index.html'),before);
 save('podcast-episodes','bad.md',{...episode,slug:'malo',audio_url:undefined});assert.throws(()=>readPodcasts(fixture));
 save('podcast-episodes','bad.md',{...episode,slug:'malo',audio_url:undefined,spotify_url:'https://example.org/episode/123abc'});assert.throws(()=>readPodcasts(fixture));
 save('podcast-episodes','bad.md',{...episode,slug:'malo',series:'no-existe'});assert.throws(()=>readPodcasts(fixture));
 fs.unlinkSync(path.join(fixture,'content/podcast-episodes/bad.md'));
 save('podcast-series','serie.md',{...series,status:'draft'});assert.throws(()=>readPodcasts(fixture));
 console.log('Pruebas correctas: series, audio nativo, Spotify, transcripción, borradores privados, generación estable y validación antes de publicar.');
}finally{fs.rmSync(fixture,{recursive:true,force:true});}
